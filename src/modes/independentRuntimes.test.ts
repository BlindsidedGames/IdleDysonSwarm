// Every launch is proven isolated here before constructing either graph:
// only Map storage; no host bridge, native paths, IDB, account/Cloud adapters,
// or default departure localStorage. Progression fixtures are generated by
// canonical progression builders (test/fixtures/progression/fixture-manifest.json).
function isolatedFixture() {
  const files = new Map<string, string>(), markerValues = new Map<string, string>()
  const storage: SaveStorageAdapter = {
    exists: async p => files.has(p), readText: async p => { if (!files.has(p)) throw Error('missing'); return files.get(p)! },
    writeText: async (p, text) => { files.set(p, text) },
    copy: async (a, b) => { files.set(b, files.get(a)!) },
    replaceAtomically: async (a, b) => { files.set(b, files.get(a)!); files.delete(a) }, discoverLegacyCandidates: async () => [],
  }
  let now = Date.parse('2026-10-15T00:00:00Z'), monotonic = 0
  const callbacks = new Map<unknown, () => void>(); let nextFrame = 0
  const codecs = { classic: createClassicModeCodec(() => new Date(now).toISOString()), modern: createModernModeCodec(() => new Date(now).toISOString()) }
  const store = new ModeSaveStore(storage, codecs, () => undefined)
  let classic: ClassicRuntime | undefined, modern: BrowserUiRuntimeFoundation | undefined
  const options = (mode: string): ModeRuntimeHostOptions => ({
    lifecycle: { currentPhase: () => 'active', subscribe: () => () => undefined },
    lifecycleClock: { sample: () => ({ utcMilliseconds: now, serializedUtcText: new Date(now).toISOString() }) },
    lifecyclePolicy: WEB_LIFECYCLE_POLICY,
    activeTimeClock: { nowMilliseconds: () => monotonic },
    activeTimeScheduler: { requestFrame: cb => { const id = ++nextFrame; callbacks.set(id, cb); return id }, cancelFrame: id => { callbacks.delete(id) } },
    nowUtcMilliseconds: () => now,
    departureMarker: new BrowserDepartureMarker('synthetic-mode-' + mode, { getItem: k => markerValues.get(k) ?? null, setItem: (k, v) => { markerValues.set(k, v) }, removeItem: k => { markerValues.delete(k) } }),
    frontendSnapshotScheduler: { requestFrame: cb => { queueMicrotask(cb); return 0 }, cancelFrame: () => undefined },
    checkpointScheduler: { setInterval: () => 0, clearInterval: () => undefined },
  })
  const controller = new GameModeController(store, {
    classic: ctx => createClassicModeSession(ctx, { ...options('classic'), attach: runtime => { classic = runtime; return () => { classic = undefined } } }),
    modern: ctx => createModernModeSession(ctx, { ...options('modern'), attach: runtime => { modern = runtime; return () => { modern = undefined } } }),
  }, convertClassicUsingExistingKeepPolicy)
  return { controller, store, codecs, get classic() { return classic }, get modern() { return modern },
    elapse: (milliseconds: number) => { now += milliseconds; monotonic += milliseconds },
    frame: async () => { const pending = [...callbacks.values()]; callbacks.clear(); for (const cb of pending) cb(); await new Promise(resolve => setTimeout(resolve, 0)) },
    callbacks,
  }
}

function generated(id: string) { return readFileSync(new URL(`../../test/fixtures/progression/${id}.idsweb1.txt`, import.meta.url), 'utf8') }

test('real mode codecs reject reverse conversion and new players open modern without a legacy choice', async () => {
  const f = isolatedFixture()
  const modern = await f.codecs.modern.createFresh(), classic = await f.codecs.classic.createFresh()
  expect(() => f.codecs.classic.validate(modern)).toThrow()
  expect(() => f.codecs.modern.validate(generated('late-quantum'))).toThrow('explicit one-way')
  expect(() => f.codecs.classic.validate(classic)).not.toThrow()
  try {
    await f.controller.start({ discovery: 'complete', saves: {} })
    expect(f.modern?.status().phase).toBe('ready')
    expect(f.classic).toBeUndefined()
    const text = await f.modern!.readCurrentSaveText()
    expect(deserializeWebSave(text!).idsReworkMigrationChoice).toBe('keep')
  } finally { await f.controller.close() }
  expect(f.callbacks.size).toBe(0)
})

test.each(['mature-simulations', 'late-quantum'])('Classic retains released systems and both saves survive real graph switching: %s', async id => {
  const f = isolatedFixture()
  try {
    await f.controller.start({ discovery: 'complete', saves: { classic: generated(id) } })
    expect(f.classic?.status().phase).toBe('ready')
    expect((await f.classic!.dispatchPlayer({ kind: 'quantum.set-buy-mode', buyMode: 'buy-10' })).status).toBe('accepted')
    const before = deserializeWebSave((await f.classic!.readCurrentSaveText())!)
    await f.controller.switchTo('modern')
    expect(f.classic).toBeUndefined()
    expect(f.modern?.status().phase).toBe('ready')
    expect((await f.modern!.dispatchPlayer({ kind: 'quantum.set-buy-mode', buyMode: 'buy-10' })).status).toBe('rejected')
    await f.controller.switchTo('classic')
    expect(f.modern).toBeUndefined()
    const after = deserializeWebSave((await f.classic!.readCurrentSaveText())!)
    expect(after.sdPrestige).toEqual(before.sdPrestige)
    expect(after.saveData).toEqual(before.saveData)
    expect(hydrateClassic(ClassicSave.fromDecoded(after)).state.dyson).toEqual(hydrateClassic(ClassicSave.fromDecoded(before)).state.dyson)
  } finally { await f.controller.close() }
  expect(f.callbacks.size).toBe(0)
})

test('active time and inactive mode offline credit settle through their own released/rework lifecycle once', async () => {
  const f = isolatedFixture()
  try {
    await f.controller.start({ discovery: 'complete', saves: { classic: await f.codecs.classic.createFresh() } })
    f.elapse(1000); await f.frame(); await f.frame()
    await f.controller.switchTo('modern')
    const classicBefore = deserializeWebSave((await f.store.read('classic'))!)
    f.elapse(3000); await f.frame(); await f.frame()
    await f.controller.switchTo('classic')
    const classicAfter = deserializeWebSave((await f.classic!.readCurrentSaveText())!)
    expect(Number(classicAfter.offlineTime) - Number(classicBefore.offlineTime)).toBeCloseTo(3, 3)
    await f.controller.switchTo('modern'); await f.controller.switchTo('classic')
    const returned = deserializeWebSave((await f.classic!.readCurrentSaveText())!)
    expect(returned.offlineTime).toBe(classicAfter.offlineTime)
    expect(hydrateClassic(ClassicSave.fromDecoded(classicBefore)).state.timeline.infinityCycleSeconds).toBeCloseTo(1, 2)
    expect(hydrateClassic(ClassicSave.fromDecoded(returned)).state.timeline.infinityCycleSeconds).toBeCloseTo(1, 2)
  } finally { await f.controller.close() }
  expect(f.callbacks.size).toBe(0)
})


test('migration through both actual runtimes preserves Classic, retains existing keep mappings and carries offline balance', async () => {
  const f = isolatedFixture()
  try {
    await f.controller.start({ discovery: 'complete', saves: { classic: generated('late-quantum') } })
    const before = hydrateClassic(ClassicSave.fromDecoded(deserializeWebSave((await f.classic!.readCurrentSaveText())!))).state
    await f.controller.migrateClassic()
    expect(f.modern?.status().phase).toBe('ready')
    const modern = deserializeWebSave((await f.modern!.readCurrentSaveText())!)
    expect(modern.idsReworkMigrationChoice).toBe('keep')
    expect(Number(modern.offlineTime)).toBe(before.timeline.storedTimeAvailableSeconds)
    await f.controller.switchTo('classic')
    const restored = hydrateClassic(ClassicSave.fromDecoded(deserializeWebSave((await f.classic!.readCurrentSaveText())!))).state
    expect(restored.quantum).toEqual(before.quantum)
    expect(restored.reality).toEqual(before.reality)
    expect(restored.dream).toEqual(before.dream)
    await expect(f.controller.migrateClassic()).rejects.toThrow('already exists')
  } finally { await f.controller.close() }
})
